namespace _11_forLoop
{
    internal class Program
    {
        static void Main(string[] args)
        {   
            // for loop => Repeat some code in finite amount of times

            Console.WriteLine("Learn for loop in C-sharp");


            for (int i=1; i<=10; i++)
            {
                
                Console.WriteLine($"7 x {i} = {7 * i}");
            }
        }
    }
}
